-- SLICE / IN MOTION — Global leaderboard setup
-- Run this entire file once in Supabase > SQL Editor.

create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  name text not null,
  name_key text not null unique,
  score integer not null default 0 check (score >= 0 and score <= 1000000),
  updated_at timestamptz not null default now()
);

alter table public.leaderboard enable row level security;

drop policy if exists "Anyone can read leaderboard" on public.leaderboard;
create policy "Anyone can read leaderboard"
on public.leaderboard
for select
to anon, authenticated
using (true);

create or replace function public.submit_score(p_name text, p_score integer)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text := left(trim(coalesce(p_name, 'PLAYER')), 12);
  v_key text;
  v_score integer := greatest(0, least(coalesce(p_score, 0), 1000000));
begin
  if v_name = '' then
    v_name := 'PLAYER';
  end if;

  v_key := lower(v_name);

  insert into public.leaderboard (name, name_key, score, updated_at)
  values (v_name, v_key, v_score, now())
  on conflict (name_key) do update
  set
    name = case
      when excluded.score > public.leaderboard.score then excluded.name
      else public.leaderboard.name
    end,
    score = greatest(public.leaderboard.score, excluded.score),
    updated_at = case
      when excluded.score > public.leaderboard.score then now()
      else public.leaderboard.updated_at
    end;
end;
$$;

revoke all on function public.submit_score(text, integer) from public;
grant execute on function public.submit_score(text, integer) to anon, authenticated;
